export const TEXTBOOK_IBANS: ReadonlySet<string> = new Set([
  ...REGISTRY_EXAMPLES,
  ...OUR_OWN_EXAMPLES,
]);

/** Normalises the way validation does: strip whitespace, upper case. */
export function isTextbookIban(iban: string | null | undefined): boolean {
  if (!iban) return false;
  return TEXTBOOK_IBANS.has(iban.replace(/\s+/g, '').toUpperCase());
}
