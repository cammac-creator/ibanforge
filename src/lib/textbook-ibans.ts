/**
 * The IBANs everybody tests with, and that therefore say nothing about demand.
 *
 * The demand ledger (demand-gaps.ts) counts the checksum-valid IBANs whose
 * bank code we could not verify, because that traffic is what tells us which
 * register to plug in next. But the ISO 13616 registry publishes one example
 * IBAN per country, every library's README repeats them, and our own docs and
 * sample creditor file use a handful more. Those get pasted into the playground
 * and the first curl of every integration; several of them carry a bank code
 * that no register allocates (CH93 0076 2011 6238 5295 7 is the textbook case,
 * counted thirteen times in two days before this file existed), so without a
 * filter the top of the ledger is the textbook, not the market.
 *
 * Matching is on the normalised IBAN (no spaces, upper case), and the guard is
 * applied at the recording site only: the validation itself, the enrichment,
 * the verdict served to the caller are all untouched.
 *
 * Every entry must pass mod-97 (textbook-ibans.test.ts checks it): a typo here
 * would silently protect nothing, and a checksum-valid typo could only ever
 * suppress the count of an IBAN nobody has.
 */

